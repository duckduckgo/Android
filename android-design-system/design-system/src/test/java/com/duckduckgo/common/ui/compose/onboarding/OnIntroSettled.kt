package com.duckduckgo.common.ui.compose.onboarding

import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import androidx.compose.runtime.getValue
import androidx.compose.runtime.rememberUpdatedState
import androidx.compose.runtime.snapshotFlow
import kotlinx.coroutines.flow.first

@Composable
internal fun DaxOnboardingDialogContentScope.OnIntroSettled(action: (animated: Boolean) -> Unit) {
    val latestAction by rememberUpdatedState(action)
    LaunchedEffect(Unit) {
        snapshotFlow { isIntroSettled }.first { it }
        latestAction(!wasIntroAnimationSkipped)
    }
}
