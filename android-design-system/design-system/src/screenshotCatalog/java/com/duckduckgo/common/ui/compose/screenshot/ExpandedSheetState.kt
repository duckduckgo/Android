package com.duckduckgo.common.ui.compose.screenshot

import androidx.compose.material3.ExperimentalMaterial3Api
import androidx.compose.material3.SheetState
import androidx.compose.material3.SheetValue
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember

/**
 * A modal bottom sheet state that starts open.
 *
 * The default state starts hidden and opens itself from a LaunchedEffect once a layout pass has measured the sheet, which Paparazzi
 * never runs, so its sheets would otherwise be captured closed. Short sheets open fully, so this is the state they settle in anyway.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun rememberExpandedSheetState(): SheetState = remember {
    SheetState(
        skipPartiallyExpanded = true,
        positionalThreshold = { 0f },
        velocityThreshold = { 0f },
        initialValue = SheetValue.Expanded,
    )
}
